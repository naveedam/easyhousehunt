const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const km = (a, b) => {
  const R = 6371, t = (d) => (d * Math.PI) / 180;
  const dLat = t(b.lat - a.lat), dLng = t(b.lng - a.lng);
  const s = Math.sin(dLat / 2) ** 2 + Math.cos(t(a.lat)) * Math.cos(t(b.lat)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(s));
};

const out = [];
const problems = [];
for (const name of [...new Set(NAMES)]) {
  const params = new URLSearchParams({
    q: `${name}, Bengaluru, Karnataka, India`,
    format: "jsonv2",
    limit: "1",
    countrycodes: "in",
    viewbox: "77.35,13.30,77.90,12.70",
    bounded: "1",
  });
  try {
    const res = await fetch(`https://nominatim.openstreetmap.org/search?${params}`, {
      headers: { "User-Agent": UA, "Accept-Language": "en" },
    });
    if (!res.ok) throw new Error("HTTP " + res.status);
    const data = await res.json();
    if (!data[0]) {
      problems.push(`${name}: not found`);
    } else {
      const lat = Number(Number(data[0].lat).toFixed(5));
      const lng = Number(Number(data[0].lon).toFixed(5));
      const d = km(CENTER, { lat, lng });
      if (d > 40) problems.push(`${name}: ${d.toFixed(0)} km from centre, check it`);
      out.push({ name, lat, lng, ...(ALIASES[name] ? { aliases: ALIASES[name] } : {}) });
    }
  } catch (e) {
    problems.push(`${name}: ${e.message}`);
  }
  process.stdout.write(".");
  await sleep(1100);
}

const header = `// Generated by scripts/build-localities.mjs on ${new Date().toISOString().slice(0, 10)}. Review before committing.
// Locations © OpenStreetMap contributors.
export type Locality = { name: string; lat: number; lng: number; aliases?: string[] };
export const LOCALITIES: Locality[] = `;
await writeFile("src/data/localities.ts", header + JSON.stringify(out, null, 1) + ";\n");
console.log(`Saved ${out.length} of ${NAMES.length} localities`);
if (problems.length) console.log("Check these by hand:\n" + problems.join("\n"));
